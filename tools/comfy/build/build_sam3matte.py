"""Builds gizmos/SAM3Matte.nk (a single Group) with Nuke's own API, so the .nk is valid by construction.

    "L:/Apps/Nuke16.1v4/Nuke16.1.exe" -t L:/Nuke/tools/comfy/build/build_sam3matte.py

Edit this script, not the .nk, and rebuild.
"""
import os
import sys

import nuke

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "python").replace("\\", "/"))
import sam3matte_crypto as crypto  # noqa: E402  (bare module, pure Python)

OUT = os.path.join(HERE, "..", "gizmos", "SAM3Matte.nk").replace("\\", "/")
N = 8

HEADER = """# SAM3Matte - mattes, per-object channels and a Cryptomatte layer from SAM3 through ComfyUI (sam3.1 multiplex)
# Generated by build/build_sam3matte.py: edit that script and rebuild, not this file.
# Generate renders the plate, sends it to ComfyUI, tracks up to 8 objects and keeps the masks as 8-bit PNG sequences
# (obj<k>.####.png) in a version folder; the Group reads them back, so a result never needs ComfyUI again.
# Inputs: Source (the plate), Select (key frame only: its alpha marks what to segment, white = include), Stencil (its alpha marks what to leave out).
# Outputs (one stream): rgb = Source untouched; rgba.alpha = union of the chosen Objects, then Erode, Blur and the optional
# Hard stencil; sam.m0 .. sam.m7 = one raw mask per object; CryptoSAM00 (red, green, blue, alpha) + manifest metadata, so a
# Cryptomatte node after this Group picks objects by name. sam.* and CryptoSAM00 are raw (no erode, blur or stencil).
# SAM3Matte's alpha plugs into Flux3Klein's Mask input (Mask channel = alpha).
# Write EXRs as 32-bit float, channels 'all', metadata 'all metadata': half float cannot hold the Cryptomatte IDs and the
# default metadata setting drops the exr/cryptomatte/* lines the Cryptomatte node needs.
# Target: Nuke 16.1. Import with the NukeComfy menu, File > Import Script, or nuke.nodePaste(path). It is not in the node toolbar.
# Tested: headless in Nuke 16.1 (tests/nuke/test_sam3matte_group.py). The Generate button needs a ComfyUI (COMFY_URL).
"""

MODE_TIP = (
    "Two ways SAM3 can work:\n"
    "\n"
    "From key frame (default)\n"
    "  Uses: Prompt, Select, Stencil, in any mix.\n"
    "  How: SAM3 Detect on the key frame, then track both ways.\n"
    "  Objects entering later: not found (generate again from a later key frame).\n"
    "  'person:2' caps: honoured.\n"
    "  Stencil: a hint (excludes points with Select; with text only, drops detected objects mostly inside Stencil) "
    "and an optional hard cut.\n"
    "\n"
    "Whole range\n"
    "  Uses: Prompt only.\n"
    "  How: SAM3 Video Track with text over the range, one forward pass.\n"
    "  Objects entering later: found as they enter.\n"
    "  'person:2' caps: ignored, only Max objects applies.\n"
    "  Stencil: hard cut only (forced on).\n"
    "\n"
    "Whole range with Select connected is an error: switch to From key frame."
)


def knob(group, k, value=None, **flags):
    group.addKnob(k)
    if value is not None:
        k.setValue(value)
    for name, on in flags.items():
        k.setFlag(getattr(nuke, name)) if on else k.clearFlag(getattr(nuke, name))
    return k


def tooltip(k, text):
    k.setTooltip(text)
    return k


def build():
    for n in nuke.allNodes():
        nuke.delete(n)
    # The pure module does not create layers; declare them before any node uses them.
    nuke.Layer("sam", crypto.SAM_CHANNELS)
    nuke.Layer(crypto.LAYER + "00", ["%s00.%s" % (crypto.LAYER, c) for c in ("red", "green", "blue", "alpha")])

    g = nuke.nodes.Group(name="SAM3Matte", tile_color=0x7a5a9bff, label="[value status]")

    # ---- SAM3Matte tab
    knob(g, nuke.Tab_Knob("sam3matte_tab", "SAM3Matte"))
    tooltip(knob(g, nuke.Enumeration_Knob("mode", "Mode", ["From key frame", "Whole range"])), MODE_TIP)
    tooltip(knob(g, nuke.String_Knob("prompt", "Prompt"), ""),
            "What to matte, comma separated: person:2, ball:1\n"
            "':N' is the most objects to keep for that subject. The caps only work in From key frame mode "
            "(Whole range ignores them and uses Max objects). Max 32 tokens.\n"
            "Empty is fine in From key frame mode if Select has strokes.")
    tooltip(knob(g, nuke.Int_Knob("max_objects", "Max objects"), 4),
            "Most objects tracked (1 to 8). Each one is a mask sequence in the version folder and a sam.m channel.")
    g["max_objects"].setRange(1, 8)
    tooltip(knob(g, nuke.Boolean_Knob("source_range", "Source range"), True, STARTLINE=True),
            "On: the Source's frame range. Off: type First and Last.")
    knob(g, nuke.Int_Knob("first", "First"), 1)
    g["first"].setEnabled(False)
    knob(g, nuke.Int_Knob("last", "Last"), 100)
    g["last"].setEnabled(False)
    g["last"].clearFlag(nuke.STARTLINE)
    tooltip(knob(g, nuke.Boolean_Knob("key_current", "Key at current frame"), True, STARTLINE=True),
            "From key frame mode: the frame SAM3 detects on. On: the frame the Viewer is on when you press Generate. "
            "Off: type Key frame.")
    knob(g, nuke.Int_Knob("key_frame", "Key frame"), 1)
    g["key_frame"].setEnabled(False)
    tooltip(knob(g, nuke.Int_Knob("tracking_width", "Tracking width"), 1024),
            "Width in pixels SAM3 tracks at (the key frame is sent at full size). Masks come back at this size and are "
            "scaled up to the plate here.")
    tooltip(knob(g, nuke.Int_Knob("chunk_size", "Chunk size"), 250),
            "Frames per ComfyUI run. Long shots are cut into chunks that share a seed mask, so memory stays flat.")
    knob(g, nuke.Text_Knob("run_div", ""))
    knob(g, nuke.PyScript_Knob("generate", "Generate",
                               "import NukeComfy.python.sam3matte\nNukeComfy.python.sam3matte.generate(nuke.thisNode())"))
    knob(g, nuke.PyScript_Knob("cancel", "Cancel",
                               "import NukeComfy.python.sam3matte\nNukeComfy.python.sam3matte.cancel(nuke.thisNode())"),
         STARTLINE=False)
    tooltip(knob(g, nuke.Enumeration_Knob("version", "Version", [" "])),
            "Every Generate adds a version; pick the one shown. A partial version can be resumed by generating again "
            "with the same settings.")
    knob(g, nuke.String_Knob("status", "Status"), "Idle")

    # ---- Matte tab
    knob(g, nuke.Tab_Knob("matte_tab", "Matte"))
    tooltip(knob(g, nuke.String_Knob("objects", "Objects"), "all"),
            "Which objects make up the alpha: all, or a comma list of slot numbers or object names (0, 2 or person_1, ball_1). "
            "Only the alpha follows this; sam.* and CryptoSAM00 always carry every object.")
    tooltip(knob(g, nuke.Double_Knob("erode", "Erode"), 0), "Shrinks the alpha, in pixels (negative grows). Alpha only.")
    g["erode"].setRange(-20, 20)
    tooltip(knob(g, nuke.Double_Knob("blur", "Blur"), 0),
            "Softens the alpha edge, in pixels. SAM3 edges are hard, so this is where they get soft. Alpha only.")
    g["blur"].setRange(0, 50)
    tooltip(knob(g, nuke.Boolean_Knob("hard_stencil", "Hard stencil"), False, STARTLINE=True),
            "Also cut the Stencil input's alpha (held at the key frame) out of the final alpha. Off: in From key frame mode "
            "Stencil is only a hint to SAM3. Always on in Whole range mode.")
    knob(g, nuke.Text_Knob("matte_div", ""))
    tooltip(knob(g, nuke.PyScript_Knob("make_roto", "Make Roto",
                                       "import NukeComfy.python.sam3matte_roto\n"
                                       "NukeComfy.python.sam3matte_roto.make_roto(nuke.thisNode())")),
            "Builds an animated Roto node next to the Group from the current version's saved masks. No ComfyUI needed.")
    tooltip(knob(g, nuke.Int_Knob("roto_points", "Points per shape"), 32),
            "Make Roto: points per shape (the same count on every frame).")
    tooltip(knob(g, nuke.Int_Knob("roto_step", "Key every N frames"), 1), "Make Roto: a key every N frames.")

    # ---- hidden state, driven from Python
    knob(g, nuke.String_Knob("versions_data", ""), "[]", INVISIBLE=True)
    knob(g, nuke.Boolean_Knob("has_result", ""), False, INVISIBLE=True)
    for name in ("stencil_frame", "mask_first", "mask_last"):
        knob(g, nuke.Int_Knob(name, ""), 0, INVISIBLE=True)
    for k in range(N):
        knob(g, nuke.Boolean_Knob("obj_present%d" % k, ""), False, INVISIBLE=True)
    for k in range(N):
        knob(g, nuke.Boolean_Knob("obj_on%d" % k, ""), True, INVISIBLE=True)

    g["knobChanged"].setValue("try:\n    import NukeComfy.python.sam3matte as s\n    s.knob_changed(nuke.thisNode(), nuke.thisKnob())\n"
                              "except ImportError:\n    pass")

    with g:
        src = nuke.nodes.Input(name="Source", number=0, xpos=0, ypos=-400)
        sel = nuke.nodes.Input(name="Select", number=1, xpos=1500, ypos=-400,
                               label="alpha marks what to segment (white = include), key frame")
        sten = nuke.nodes.Input(name="Stencil", number=2, xpos=1700, ypos=-400,
                                label="alpha marks what to leave out")

        black = nuke.nodes.Multiply(name="Black", channels="all", value=0, xpos=-200, ypos=-300)
        black.setInput(0, src)

        stream = src
        for k in range(N):
            x = 200 + 160 * k
            rd = nuke.nodes.Read(name="Obj%dRead" % k, raw=True, on_error="black", before="black", after="black",
                                 xpos=x, ypos=-320)
            rf = nuke.nodes.Reformat(name="Obj%dScale" % k, type="to box", box_fixed=True, resize="distort",
                                     filter="linear", xpos=x, ypos=-260)
            rf["box_width"].setExpression("Source.width")
            rf["box_height"].setExpression("Source.height")
            rf.setInput(0, rd)
            sw = nuke.nodes.Switch(name="Obj%dSlot" % k, xpos=x, ypos=-200)
            sw.setInput(0, black)
            sw.setInput(1, rf)
            sw["which"].setExpression("parent.obj_present%d" % k)
            cp = nuke.nodes.Copy(name="Obj%dCopy" % k, from0="rgba.red", to0="sam.m%d" % k, xpos=x, ypos=-120 + 40 * k)
            cp.setInput(0, stream)
            cp.setInput(1, sw)
            stream = cp

        # Cryptomatte layer, built straight after the per-object copies. CryptoExpr writes id0, cov0 and id1 (red, green, blue).
        # Nuke's channel selector cannot pick "CryptoSAM00.alpha" on an Expression (it falls back to "none"; sam3matte_crypto
        # sets it anyway and a later apply_to_nodes will do so again), so cov1 is computed by CryptoCov1, which reads CryptoExpr's
        # expr3 string live, into rgba.alpha as a scratch channel, and CryptoAlpha copies it into CryptoSAM00.alpha with a Copy.
        # The real alpha is written afterwards by Union.
        cexpr = nuke.nodes.Expression(name="CryptoExpr", xpos=0, ypos=100)
        cexpr.setInput(0, stream)
        cov1 = nuke.nodes.Expression(name="CryptoCov1", channel0="rgba.alpha", channel1="none", channel2="none",
                                     channel3="none", xpos=0, ypos=160)
        cov1["expr0"].setValue("[value CryptoExpr.expr3]")
        cov1.setInput(0, cexpr)
        calpha = nuke.nodes.Copy(name="CryptoAlpha", from0="rgba.alpha", to0="CryptoSAM00.alpha", xpos=0, ypos=220)
        calpha.setInput(0, cexpr)
        calpha.setInput(1, cov1)
        stream = calpha

        union = nuke.nodes.Expression(name="Union", channel0="none", channel1="none", channel2="none",
                                      channel3="rgba.alpha", expr3="max(%s)" % ", ".join(
                                          "parent.obj_on%d * sam.m%d" % (k, k) for k in range(N)),
                                      xpos=0, ypos=300)
        union.setInput(0, stream)
        erode = nuke.nodes.FilterErode(name="Erode", channels="alpha", xpos=0, ypos=360)
        erode["size"].setExpression("parent.erode")
        erode.setInput(0, union)
        soften = nuke.nodes.Blur(name="Soften", channels="alpha", xpos=0, ypos=420)
        soften["size"].setExpression("parent.blur")
        soften.setInput(0, erode)

        hold = nuke.nodes.FrameHold(name="StencilHold", xpos=1700, ypos=-320)
        hold["firstFrame"].setExpression("parent.stencil_frame")
        hold.setInput(0, sten)
        # Merge's stencil on the alpha channel alone does nothing in Nuke 16.1, so stencil rgba and copy only alpha back.
        cut = nuke.nodes.Merge2(name="StencilCut", operation="stencil", Achannels="rgba", Bchannels="rgba",
                                output="rgba", xpos=0, ypos=480)
        cut.setInput(0, soften)    # B
        cut.setInput(1, hold)      # A
        cut["disable"].setExpression("!(parent.hard_stencil || parent.mode == 1)")   # Whole range always cuts
        back = nuke.nodes.Copy(name="StencilAlpha", from0="rgba.alpha", to0="rgba.alpha", xpos=0, ypos=520)
        back.setInput(0, soften)
        back.setInput(1, cut)

        cmeta = nuke.nodes.ModifyMetaData(name="CryptoMeta", xpos=0, ypos=620)
        cmeta.setInput(0, back)
        crypto.apply_to_nodes(cexpr, cmeta, [None] * N)
        nuke.nodes.Output(name="Output1", xpos=0, ypos=700).setInput(0, cmeta)

    for n in nuke.allNodes():
        n.setSelected(False)
    g.setSelected(True)
    nuke.nodeCopy(OUT)
    with open(OUT, encoding="utf-8") as f:
        body = f.read()
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER + body)
    print("wrote", OUT)


build()
