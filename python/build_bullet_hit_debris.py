"""Builds the BulletHitDebris Group and exports gizmos/BulletHitDebris.nk.

Target: Nuke 16 (baseline). Run headless:
    L:/Apps/Nuke16.1v4/Nuke16.1.exe -t python/build_bullet_hit_debris.py

The exported .nk is a single top-level Group -- import it with
nuke.nodePaste(path), File > Import Script, or by pasting its text into the
node graph. It does NOT appear in the node toolbar (it is not a .gizmo).

What the group does: a one-shot particle burst for a bullet hit on a surface
(a table top). Everything is simulated in a canonical space -- hit at the
origin, surface = the y=0 plane, +Y = surface normal, 1 unit = 1 metre --
then moved into the shot by TransformGeo (Placement, or the axis input).
Two particle systems, rendered separately:
  debris : tumbling chips / splinters, gravity, bounce on the table, spin.
  dust   : fast spray (heavy drag) + a slow puff at the hit point.
All particles are born in the impact frame. Colour and the fade-out are done
in 2D after each render, because Nuke 16 ignores particle colour/alpha on
textured particles. The fade is driven by frame - impact_frame, so with the
defaults: impact = frame 1, main throw = 2-5, fade = 5-8, impact+8 is empty.
Image sprites are not used either: in Nuke 16 they ignore the emitter size.
No external files: every shape is procedural, so the snippet pastes anywhere.
Internal expressions use parent.<knob>, so several copies can live in one script.
"""
import os
import nuke

OUT_PATH = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                        "gizmos", "BulletHitDebris.nk")

HEADER = """\
# BulletHitDebris -- particle debris + dust spray burst for a bullet hit   (target: Nuke 16)
# Import: nuke.nodePaste("<path>/BulletHitDebris.nk"), File > Import Script, or paste
#         this text into the Node Graph. NOT a .gizmo -- it will not be in the toolbar.
# Inputs: img  plate (sets the output format)
#         cam  shot camera. Connect one: Nuke's default camera sits inside the burst.
#              No solve? Use any Camera looking at the table and place by eye.
#         axis optional parent for the placement, e.g. an Axis / CameraTracker locator on the table
# Output: img with the burst merged over, or the premultiplied burst alone ("output" knob).
# Timing: impact_frame = impact, +1..+4 main throw, fade to 0 by impact+8 (life knob).
# Space : hit at origin, table = y=0 plane, +Y up, 1 unit = 1 m. Use "scene scale" for cm scenes.
# Needs: NukeX / Nuke Studio licence (particle nodes), on the farm too.
# Velocities and gravity are per frame, tuned for 24 fps.
# Paste one per hit; give each its own impact_frame and seed.
# Status: tested headless in Nuke 16.1v4 on a synthetic table shot; not yet on a real plate.
# Generated by python/build_bullet_hit_debris.py -- edit the script, not this file.
"""

SPRITE_FMT = "128 128 0 0 128 128 1 BHD_sprite"

# ParticleEmitter "rate" is particles per frame. Emit during the frame before impact, so the
# impact frame already shows a young burst; the [impact-1, impact) window keeps the total
# right when steps_per_frame > 1.
RATE = "frame >= parent.impact_frame - 1 && frame < parent.impact_frame ? %s : 0"

# Fade multiplier: 1 until parent.<start> frames after impact, linear to 0 at impact + life.
FADE = ("(frame < parent.impact_frame ? 0 : "
        "clamp((parent.impact_frame + parent.life - frame) / max(1, parent.life - parent.%s)))")


def _place(n, x, y):
    n.setXYpos(x, y)
    return n


def _shape(name, kind, canvas, x, y, tone=1.0):
    """Premultiplied alpha shape on the small sprite format (no Read nodes).

    dust     soft radial broken up by noise
    chunk    solid irregular chip: a radial with noise bites out of its edge
    splinter thin jagged sliver
    tone     brightness of the shape, so chips vary in value
    """
    if kind == "dust":
        base = nuke.nodes.Radial(inputs=[canvas], softness=1)
        base["area"].setValue([8, 8, 120, 120])
        size, lo, hi = 16, 0.2, 0.7
    elif kind == "chunk":
        base = nuke.nodes.Radial(inputs=[canvas], softness=0.1)
        base["area"].setValue([10, 20, 118, 108])
        size, lo, hi = 45, 0.12, 0.2
    elif kind == "splinter":
        base = nuke.nodes.Rectangle(inputs=[canvas], softness=3)
        base["area"].setValue([50, 0, 78, 128])
        size, lo, hi = 14, 0.18, 0.24
    else:
        raise ValueError(kind)
    base.setName(name + "_base")
    _place(base, x, y)
    noise = _place(nuke.nodes.Noise(name=name + "_noise", inputs=[canvas]), x + 110, y)
    noise["output"].setValue("alpha")
    noise["size"].setValue(size)
    noise["zoffset"].setValue(len(name) * 1.7)
    # threshold the noise into a mask
    thr = _place(nuke.nodes.Grade(name=name + "_thr", inputs=[noise], channels="alpha"), x + 110, y + 40)
    thr["blackpoint"].setValue(lo)
    thr["whitepoint"].setValue(hi)
    thr["white_clamp"].setValue(True)
    m = _place(nuke.nodes.Merge2(name=name + "_mask", inputs=[base, thr], operation="mask",
                                 output="alpha"), x, y + 80)
    # rgb = alpha * tone
    out = _place(nuke.nodes.Expression(name=name, inputs=[m]), x, y + 120)
    out["channel0"].setValue("rgb")
    out["expr0"].setValue("a * %g" % tone)
    out["channel3"].setValue("alpha")
    out["expr3"].setValue("a")
    return out


def _card(name, img, x, y):
    """Particle instance: a 1x1 card textured with img."""
    c = _place(nuke.nodes.Card2(name=name, inputs=[img]), x, y)
    c["rows"].setValue(1)
    c["columns"].setValue(1)
    return c


def _knob(g, k, value=None, tip=None):
    g.addKnob(k)
    if value is not None:
        k.setValue(value)
    if tip:
        k.setTooltip(tip)
    return k


def _double(g, name, label, value, lo, hi, tip=None):
    k = _knob(g, nuke.Double_Knob(name, label), value, tip)
    k.setRange(lo, hi)
    return k


def build():
    nuke.addFormat(SPRITE_FMT)
    g = nuke.nodes.Group(name="BulletHitDebris")

    # ------------------------------------------------------------ user knobs
    _knob(g, nuke.Tab_Knob("tab_main", "BulletHitDebris"))
    _knob(g, nuke.Int_Knob("impact_frame", "impact frame"), 1,
          "Frame the bullet lands. Every particle is born in this frame.")
    _knob(g, nuke.Int_Knob("seed", "seed"), 1, "Change per hit so two hits never look the same.")
    k = _knob(g, nuke.Enumeration_Knob("output", "output", ["comp over img", "burst only"]))
    k.clearFlag(nuke.STARTLINE)
    _knob(g, nuke.Text_Knob("div_place", "Placement"))
    _knob(g, nuke.Link_Knob("place_translate", "position"))
    _knob(g, nuke.Link_Knob("place_rotate", "surface rotate"))
    _knob(g, nuke.Link_Knob("place_scale", "scene scale"))
    _knob(g, nuke.XYZ_Knob("throw_dir", "throw tilt"), None,
          "Tilts the burst away from the surface normal (degrees). "
          "Lean it back toward the shooter for an angled hit.")

    _knob(g, nuke.Text_Knob("div_debris", "Debris (chips / splinters)"))
    _double(g, "debris_count", "amount", 150, 0, 800, "Chips in the burst.")
    _double(g, "debris_speed", "speed", 0.06, 0, 0.4, "Metres per frame at birth.")
    _double(g, "debris_size", "size", 0.012, 0, 0.05, "Chip size, metres.")
    _double(g, "debris_spread", "spread", 0.4, 0, 1, "0 = straight up the normal, 1 = wide.")
    _double(g, "debris_spin", "spin", 40, 0, 120, "Tumble rate.")
    _double(g, "debris_bounce", "bounce", 0.3, 0, 1, "How much chips bounce off the table.")
    _knob(g, nuke.Color_Knob("debris_color", "colour"), [0.32, 0.2, 0.11])
    _double(g, "debris_fade", "fade starts", 4, 0, 12, "Frames after impact where debris starts to fade.")

    _knob(g, nuke.Text_Knob("div_spray", "Spray (dust)"))
    _double(g, "spray_count", "amount", 1200, 0, 4000, "Dust particles in the burst.")
    _double(g, "spray_speed", "speed", 0.09, 0, 0.6, "Metres per frame at birth.")
    _double(g, "spray_size", "size", 0.007, 0, 0.05, "Dust particle size, metres.")
    _double(g, "spray_spread", "spread", 0.35, 0, 1)
    _double(g, "spray_drag", "drag", 0.4, 0, 1, "Slows the dust down fast after the hit.")
    _double(g, "puff_count", "impact puff", 80, 0, 300,
            "Slow, larger dust right at the hit point: the impact-frame read.")
    _double(g, "puff_size", "puff size", 0.04, 0, 0.1)
    _knob(g, nuke.Color_Knob("spray_color", "colour"), [0.6, 0.53, 0.45])
    _double(g, "spray_opacity", "opacity", 0.7, 0, 1)
    _double(g, "spray_fade", "fade starts", 2, 0, 12, "Frames after impact where dust starts to thin out.")

    _knob(g, nuke.Text_Knob("div_sim", "Simulation / render"))
    _double(g, "gravity", "gravity", 1, 0, 3, "1 = earth gravity at 24 fps, metres.")
    _double(g, "life", "life (frames)", 8, 3, 24, "Frames from impact until everything has faded out.")
    _knob(g, nuke.Boolean_Knob("table_holdout", "table holdout"), True,
          "Invisible table top at y=0 that hides particles below the surface (e.g. with a strong throw tilt).")
    _knob(g, nuke.Link_Knob("mb_samples", "motion blur samples"))
    _knob(g, nuke.Link_Knob("mb_shutter", "shutter"))
    _knob(g, nuke.Link_Knob("nudge_translate", "2D nudge"))

    g.begin()
    # ---------------------------------------------------------------- inputs
    inp_img = _place(nuke.nodes.Input(name="img"), 0, -700)
    inp_cam = _place(nuke.nodes.Input(name="cam"), 1500, 600)
    inp_axis = _place(nuke.nodes.Input(name="axis"), 1300, 380)
    inp_img["number"].setValue(0)
    inp_cam["number"].setValue(1)
    inp_axis["number"].setValue(2)

    # --------------------------------------------------------------- shapes
    canvas = _place(nuke.nodes.Constant(name="sprite_canvas", format="BHD_sprite"), 250, -520)
    canvas["color"].setValue(0)
    dust = _shape("dust", "dust", canvas, 0, -400)
    chunk = _shape("chunk", "chunk", canvas, 250, -400)
    chunk_dark = _shape("chunk_dark", "chunk", canvas, 500, -400, tone=0.55)
    splinter = _shape("splinter", "splinter", canvas, 750, -400, tone=0.8)
    cards_debris = [_card("chunk_card", chunk, 250, -200),
                    _card("chunk_dark_card", chunk_dark, 500, -200),
                    _card("splinter_card", splinter, 750, -200)]
    card_dust = _card("dust_card", dust, 0, -200)

    # Emitters have no emit geometry: they shoot along their own +Y (the table normal),
    # spread into a cone, and their rotate knob tilts that cone by throw_dir.
    # Emitting from card points was tried: point normals point every way, half the
    # burst went into the table.

    def emitter(name, upstream, shapes, ch, count, x, seed_offset):
        e = _place(nuke.nodes.ParticleEmitter(name=name), x, -100)
        e.setInput(0, upstream)
        for i, s in enumerate(shapes):
            e.setInput(2 + i, s)
        e["emit_channels"].setValue(ch)
        for i, c in enumerate("xyz"):
            e["rotate"].setExpression("parent.throw_dir.%s" % c, i)
        e["start_frame"].setExpression("parent.impact_frame - 2")
        e["rate"].setExpression(RATE % count)
        e["seed"].setExpression("parent.seed * 13 + %d" % seed_offset)
        # outlive the 2D fade so nothing pops off before it reaches 0
        e["lifetime"].setExpression("parent.life + 2")
        return e

    # ---- debris system
    e_debris = emitter("emit_debris", None, cards_debris, 1, "parent.debris_count", 500, 1)
    e_debris["velocity"].setExpression("parent.debris_speed")
    e_debris["velocity_variation"].setValue(0.75)
    e_debris["size"].setExpression("parent.debris_size")
    e_debris["size_variation"].setValue(0.8)
    e_debris["spread"].setExpression("parent.debris_spread")
    e_debris["rotation_velocity"].setExpression("parent.debris_spin")
    e_debris["rotation_velocity_variation"].setValue(1)
    drag_debris = _place(nuke.nodes.ParticleDrag(name="drag_debris", inputs=[e_debris]), 500, 0)
    drag_debris["drag"].setValue(0.04)
    drag_debris["rotational_drag"].setValue(0.1)
    grav_debris = _place(nuke.nodes.ParticleGravity(name="gravity_debris", inputs=[drag_debris]), 500, 40)
    # 9.8 m/s^2 at 24 fps = 0.017 m/frame^2
    grav_debris["to"].setExpression("-0.017 * parent.gravity", 1)
    bounce = _place(nuke.nodes.ParticleBounce(name="table_bounce", inputs=[grav_debris]), 500, 80)
    bounce["out_bounce"].setExpression("parent.debris_bounce")
    bounce["out_friction"].setValue(0.5)
    bounce["in_bounce"].setExpression("parent.debris_bounce")
    bounce["in_friction"].setValue(0.5)
    sim_debris = _place(nuke.nodes.ParticleSettings(name="sim_debris", inputs=[bounce]), 500, 120)
    sim_debris["steps_per_frame"].setValue(3)

    # ---- dust system: spray + impact puff
    e_spray = emitter("emit_spray", None, [card_dust], 1, "parent.spray_count", 1000, 3)
    e_spray["velocity"].setExpression("parent.spray_speed")
    e_spray["velocity_variation"].setValue(0.8)
    e_spray["size"].setExpression("parent.spray_size")
    e_spray["size_variation"].setValue(0.7)
    e_spray["spread"].setExpression("parent.spray_spread")
    e_spray["rotation_velocity"].setValue(15)
    e_spray["rotation_velocity_variation"].setValue(1)
    e_puff = emitter("emit_puff", e_spray, [card_dust], 2, "parent.puff_count", 1250, 5)
    e_puff["velocity"].setExpression("parent.spray_speed * 0.12")
    e_puff["velocity_variation"].setValue(1)
    e_puff["size"].setExpression("parent.puff_size")
    e_puff["size_variation"].setValue(0.5)
    e_puff["spread"].setValue(1)
    e_puff["rotation_velocity"].setValue(5)
    e_puff["rotation_velocity_variation"].setValue(1)
    drag_dust = _place(nuke.nodes.ParticleDrag(name="drag_dust", inputs=[e_puff]), 1000, 0)
    drag_dust["drag"].setExpression("parent.spray_drag")
    grav_dust = _place(nuke.nodes.ParticleGravity(name="gravity_dust", inputs=[drag_dust]), 1000, 40)
    grav_dust["to"].setExpression("-0.006 * parent.gravity", 1)
    turb = _place(nuke.nodes.ParticleTurbulence(name="dust_turbulence", inputs=[grav_dust]), 1000, 80)
    turb["strength"].setValue([0.01, 0.006, 0.01])
    turb["scale"].setValue([0.05, 0.05, 0.05])
    sim_dust = _place(nuke.nodes.ParticleSettings(name="sim_dust", inputs=[turb]), 1000, 120)
    sim_dust["steps_per_frame"].setValue(2)

    # ------------------------------------------------------------ placement
    axis = _place(nuke.nodes.Axis2(name="Placement", inputs=[inp_axis]), 1300, 440)
    # Holdout table top: FillMat (black, alpha 0) occludes without adding colour. Sits 3 mm
    # under y=0 so chips resting on the table are not cut in half.
    fill = _place(nuke.nodes.FillMat(name="holdout_mat"), 750, 300)
    top = _place(nuke.nodes.Card2(name="holdout_table", inputs=[fill]), 750, 340)
    top["orientation"].setValue("ZX")
    top["uniform_scale"].setValue(6)
    top["translate"].setValue([0, -0.003, 0])
    top["disable"].setExpression("!parent.table_holdout")
    scene_debris = _place(nuke.nodes.MergeGeo(name="debris_and_table", inputs=[sim_debris, top]), 500, 400)
    scene_dust = _place(nuke.nodes.MergeGeo(name="dust_and_table", inputs=[sim_dust, top]), 1000, 400)
    place_debris = _place(nuke.nodes.TransformGeo(name="place_debris", inputs=[scene_debris]), 500, 480)
    place_debris.setInput(1, axis)
    place_dust = _place(nuke.nodes.TransformGeo(name="place_dust", inputs=[scene_dust]), 1000, 480)
    place_dust.setInput(1, axis)

    # --------------------------------------------------------------- render
    black = _place(nuke.nodes.Remove(name="bg_black", inputs=[inp_img]), 0, 500)
    black["operation"].setValue("remove")
    black["channels"].setValue("all")  # no plate depth reaches the render's z-buffer

    def render(name, geo, x):
        r = _place(nuke.nodes.ScanlineRender(name=name), x, 600)
        r.setInput(0, black)
        r.setInput(1, geo)
        r.setInput(2, inp_cam)
        r["shutteroffset"].setValue("centred")
        return r

    r_debris = render("render", place_debris, 500)  # owns the exposed motion blur knobs
    r_debris["samples"].setValue(10)
    # particle subframe motion reads long in Nuke; 0.3 keeps the spray streaks believable
    r_debris["shutter"].setValue(0.3)
    r_dust = render("render_dust", place_dust, 1000)
    r_dust["samples"].setExpression("parent.mb_samples")
    r_dust["shutter"].setExpression("parent.mb_shutter")

    col_debris = _place(nuke.nodes.Multiply(name="debris_colour", inputs=[r_debris], channels="rgb"), 500, 680)
    col_debris["value"].setSingleValue(False)
    for i, c in enumerate("rgb"):
        col_debris["value"].setExpression("parent.debris_color.%s" % c, i)
    fade_debris = _place(nuke.nodes.Multiply(name="debris_fadeout", inputs=[col_debris], channels="rgba"), 500, 720)
    fade_debris["value"].setExpression(FADE % "debris_fade")
    col_dust = _place(nuke.nodes.Multiply(name="dust_colour", inputs=[r_dust], channels="rgb"), 1000, 680)
    col_dust["value"].setSingleValue(False)
    for i, c in enumerate("rgb"):
        col_dust["value"].setExpression("parent.spray_color.%s" % c, i)
    fade_dust = _place(nuke.nodes.Multiply(name="dust_fadeout", inputs=[col_dust], channels="rgba"), 1000, 720)
    fade_dust["value"].setExpression("parent.spray_opacity * " + FADE % "spray_fade")
    # debris reads in front of the dust
    burst = _place(nuke.nodes.Merge2(name="debris_over_dust", inputs=[fade_dust, fade_debris]), 750, 780)

    nudge = _place(nuke.nodes.Transform(name="nudge2d", inputs=[burst]), 750, 840)
    over = _place(nuke.nodes.Merge2(name="over_plate", inputs=[inp_img, nudge]), 0, 900)
    sw = _place(nuke.nodes.Switch(name="output_switch", inputs=[over, nudge]), 0, 960)
    sw["which"].setExpression("parent.output")
    _place(nuke.nodes.Output(name="Output1", inputs=[sw]), 0, 1020)
    g.end()

    # link knobs need their targets to exist
    for knob, target in (("place_translate", "Placement.translate"),
                         ("place_rotate", "Placement.rotate"),
                         ("place_scale", "Placement.uniform_scale"),
                         ("mb_samples", "render.samples"),
                         ("mb_shutter", "render.shutter"),
                         ("nudge_translate", "nudge2d.translate")):
        g[knob].setLink(target)
    return g


def export(g):
    for n in nuke.allNodes():
        n.setSelected(False)
    g.setSelected(True)
    nuke.nodeCopy(OUT_PATH)
    with open(OUT_PATH, "r") as f:
        body = f.read()
    with open(OUT_PATH, "w", newline="\n") as f:
        f.write(HEADER + body)
    print("wrote", OUT_PATH)


if __name__ == "__main__":
    export(build())
