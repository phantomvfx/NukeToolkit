"""Builds the AOV_Beauty Group and exports gizmos/AOV_Beauty.nk.

Target: Nuke 16 (baseline). Run headless:
    Nuke16.1.exe -t python/build_aov_beauty.py

The exported .nk is a single top-level Group -- import it with
nuke.nodePaste(path), File > Import Script, or by pasting its text into the
node graph. It does NOT appear in the node toolbar (it is not a .gizmo).

Rebuild (Arnold-style light-path AOVs, all linear):
    beauty = (diffuse_direct + diffuse_indirect)            [* albedo, OFF by default:
             Arnold's diffuse AOVs already include albedo; verified ~2% off on real data]
             + specular_direct + specular_indirect + coat + sheen + sss
             + transmission + emission + volume_direct + volume_indirect
Every AOV gets Grade + ColorCorrect controls and an enable toggle (off = the AOV
contributes nothing; the albedo toggle = multiply diffuse by albedo, default off). A master Grade/ColorCorrect
sits on the sum. "view" switches between rebuilt / original RGBA_default /
difference (x gain) / untouched input.

Not used in the sum: albedoColor, direct, indirect, shw_all (kept in the stream).
"""
import os
import nuke

OUT_PATH = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                        "gizmos", "AOV_Beauty.nk")

HEADER = """\
# AOV_Beauty -- beauty rebuild from light-path AOVs with per-AOV grading   (target: Nuke 16)
# Import: nuke.nodePaste("<path>/AOV_Beauty.nk"), File > Import Script, or paste
#         this text into the Node Graph. NOT a .gizmo -- it will not be in the toolbar.
# Input : EXR with layers diffuse_direct, diffuse_indirect, albedo, specular_direct,
#         specular_indirect, coat, sheen, sss, transmission, emission, volume_direct,
#         volume_indirect (+ RGBA_default for the difference check).
# Output: input with rgba replaced by the rebuilt beauty (see "view" on the Check tab).
# Generated by python/build_aov_beauty.py -- edit the script, not this file.
"""

# key, label, how it enters the sum
AOVS = [
    ("diffuse_direct",    "Diffuse direct",    "diffuse"),
    ("diffuse_indirect",  "Diffuse indirect",  "diffuse"),
    ("albedo",            "Multiply diffuse by albedo (OFF for Arnold)", "albedo"),
    ("specular_direct",   "Specular direct",   "plus"),
    ("specular_indirect", "Specular indirect", "plus"),
    ("coat",              "Coat",              "plus"),
    ("sheen",             "Sheen",             "plus"),
    ("sss",               "SSS",               "plus"),
    ("transmission",      "Transmission",      "plus"),
    ("emission",          "Emission",          "plus"),
    ("volume_direct",     "Volume direct",     "plus"),
    ("volume_indirect",   "Volume indirect",   "plus"),
]
EXTRA_LAYERS = ["albedoColor", "direct", "indirect", "shw_all"]


def _layer(name, with_alpha=False):
    chans = ["red", "green", "blue"] + (["alpha"] if with_alpha else [])
    nuke.Layer(name, ["%s.%s" % (name, c) for c in chans])


def _merge(b, a, op, mix_expr=None, name=None):
    m = nuke.nodes.Merge2(inputs=[b, a], operation=op, name=name or "Merge")
    m["Achannels"].setValue("rgb")
    m["Bchannels"].setValue("rgb")
    m["output"].setValue("rgb")
    if mix_expr:
        m["mix"].setExpression(mix_expr)
    return m


def build():
    for key, _, _ in AOVS:
        _layer(key)
    for key in EXTRA_LAYERS:
        _layer(key)
    _layer("RGBA_default", with_alpha=True)

    g = nuke.nodes.Group(name="AOV_Beauty")

    # Per-AOV Shuffle/Grade/ColorCorrect are created first so Link knobs can point at
    # them (a plain Channel/Color knob would not round-trip through the .nk cleanly).
    chain = {}
    with g:
        inp = nuke.nodes.Input(name="src")
        for i, (key, _, _) in enumerate(AOVS):
            sh = nuke.nodes.Shuffle(name="Sh_" + key, inputs=[inp])
            sh["in"].setValue(key)
            sh["out"].setValue("rgba")
            gr = nuke.nodes.Grade(name="Grade_" + key, inputs=[sh])
            cc = nuke.nodes.ColorCorrect(name="CC_" + key, inputs=[gr])
            for n, y in ((sh, 0), (gr, 60), (cc, 120)):
                n["xpos"].setValue(i * 110)
                n["ypos"].setValue(y)
            chain[key] = (sh, gr, cc)
        mgr = nuke.nodes.Grade(name="Grade_master")
        mcc = nuke.nodes.ColorCorrect(name="CC_master", inputs=[mgr])

    def k(knob):
        g.addKnob(knob)
        return knob

    def link(name, label, node, knob_name):
        lk = nuke.Link_Knob(name, label)
        lk.makeLink(node.fullName(), knob_name)
        return k(lk)

    # ---- UI ---------------------------------------------------------------
    k(nuke.Tab_Knob("tab_master", "Master"))
    link("master_gain", "gain", mgr, "multiply")
    link("master_offset", "offset", mgr, "add")
    link("master_gamma", "gamma", mgr, "gamma")
    link("master_sat", "saturation", mcc, "saturation")
    link("master_contrast", "contrast", mcc, "contrast")

    k(nuke.Tab_Knob("tab_aov", "AOVs"))
    for key, label, _ in AOVS:
        sh, gr, cc = chain[key]
        k(nuke.Text_Knob("hdr_" + key, label, ""))
        k(nuke.Boolean_Knob(key + "_on", "enable"))
        # Arnold's diffuse AOVs already contain albedo: multiplying again darkens (~1/3 on
        # real data), so the albedo multiply is OFF by default.
        g[key + "_on"].setValue(key != "albedo")
        link(key + "_mult", "gain", gr, "multiply")
        link(key + "_add", "offset", gr, "add")
        link(key + "_gamma", "gamma", gr, "gamma")
        link(key + "_sat", "saturation", cc, "saturation")

    k(nuke.Tab_Knob("tab_check", "Check"))
    k(nuke.Enumeration_Knob("view", "view", [
        "rebuilt", "original (RGBA_default)", "difference (x gain)", "input untouched"]))
    k(nuke.Double_Knob("diff_gain", "difference gain"))
    g["diff_gain"].setValue(10.0)
    k(nuke.Text_Knob("check_hint", "",
                     "Difference = |rebuilt - RGBA_default|. Black = the rebuild matches. "
                     "albedoColor / direct / indirect / shw_all are not part of the sum."))

    # ---- wiring -----------------------------------------------------------
    with g:
        def branch(key):
            return chain[key][2]

        # The first diffuse AOV is the Merge B input, which has no mix: gate it with a Multiply.
        first = AOVS[0][0]
        gate = nuke.nodes.Multiply(name="Gate_" + first)
        gate.setInput(0, branch(first))
        gate["value"].setExpression("parent.%s_on" % first)
        diff_sum = None
        for key, _, role in AOVS:
            if role != "diffuse":
                continue
            if key == first:
                diff_sum = gate
            else:
                diff_sum = _merge(diff_sum, branch(key), "plus", "parent.%s_on" % key, "Add_" + key)

        total = _merge(diff_sum, branch("albedo"), "multiply", "parent.albedo_on", "Mul_albedo")
        for key, _, role in AOVS:
            if role == "plus":
                total = _merge(total, branch(key), "plus", "parent.%s_on" % key, "Add_" + key)

        mgr.setInput(0, total)
        mcc.setInput(0, mgr)
        keep_alpha = nuke.nodes.Copy(name="Alpha_from_src", inputs=[mcc, inp])
        keep_alpha["from0"].setValue("rgba.alpha")
        keep_alpha["to0"].setValue("rgba.alpha")

        orig = nuke.nodes.Shuffle(name="Sh_original", inputs=[inp])
        orig["in"].setValue("RGBA_default")
        orig["out"].setValue("rgba")
        diff = _merge(orig, keep_alpha, "difference", None, "Diff")
        gain = nuke.nodes.Multiply(name="Diff_gain", inputs=[diff])
        gain["value"].setExpression("parent.diff_gain")
        gain["channels"].setValue("rgb")

        sw = nuke.nodes.Switch(name="View", inputs=[keep_alpha, orig, gain, inp])
        sw["which"].setExpression("parent.view")
        nuke.nodes.Output(inputs=[sw])
    return g


def main():
    for n in nuke.allNodes():
        nuke.delete(n)
    g = build()
    for n in nuke.allNodes():
        n["selected"].setValue(n is g)
    tmp = OUT_PATH + ".tmp"
    nuke.nodeCopy(tmp)
    with open(tmp) as f:
        body = f.read()
    os.remove(tmp)
    with open(OUT_PATH, "w") as f:
        f.write(HEADER + body)
    print("WROTE", OUT_PATH)


main()
