"""Builds the InjectionScar Group and exports gizmos/InjectionScar.nk.

Target: Nuke 16 (baseline). Run headless:
    Nuke16.1.exe -t python/build_injection_scar.py

Procedural needle / injection mark on skin, fully analytic (no textures, no
extra inputs, resolution independent). The plate itself is never replaced: the
effect is a chain of Grade nodes limited by a procedural matte, so the plate's
own grain, softness and skin texture stay in the result.

Matte branch (src -> Expression -> Expression -> Blur):
  Scar_geo   r = warped distance for the puncture, g = warped distance for the
             bruise (large-scale fBm), b = mottle noise 0..1
  Scar_masks r = puncture core, g = redness ring, b = inner bruise,
             a = outer bruise (yellow/green fringe)
  Scar_soften  Blur on the masks, to match a soft plate

Grade chain (each one reads one matte channel through its mask input):
  outer bruise -> inner bruise -> redness -> core
"""
import os
import nuke

OUT_PATH = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                        "gizmos", "InjectionScar.nk")

HEADER = """\
# InjectionScar -- procedural needle / injection mark: puncture, redness ring, bruise halo   (target: Nuke 16)
# Inputs : src = the skin plate (rgba). Nothing else.
# Output : the plate with the mark graded in. Tick "show matte" to see the masks
#          (r = puncture, g = redness, b = inner bruise, a = outer bruise).
# Target : Nuke 16
# Import : NOT a .gizmo. Paste this text into the Node Graph, or use File > Import Script,
#          or nuke.nodePaste("<path>/InjectionScar.nk"). It will not be in the node toolbar.
# Use    : connect the plate, drag "position" onto the skin (or link it to a Tracker), then
#          dial size / bruise to taste. Sizes are in plate pixels.
# Status : python/smoke_injection_scar.py passes headless in Nuke 16.1v4 (synthetic plate + a real skin still).
#          Not yet checked in the GUI or pasted through the clipboard. 16.0+ expected, verified in 16.1v4.
#          The colour tints are plain multiplies: tuned on an sRGB-viewed plate, retune for a very different grade.
# Generated by python/build_injection_scar.py -- edit the script, not this file.
"""

P = "parent."


def build():
    g = nuke.nodes.Group(name="InjectionScar")
    g["tile_color"].setValue(0x8a4a4aff)

    g.addKnob(nuke.Tab_Knob("tab_scar", "InjectionScar"))

    def dbl(name, label, val, lo, hi, tip=""):
        k = nuke.Double_Knob(name, label)
        k.setRange(lo, hi)
        k.setValue(val)
        if tip:
            k.setTooltip(tip)
        g.addKnob(k)
        return k

    def col(name, label, rgb, tip=""):
        k = nuke.Color_Knob(name, label)
        g.addKnob(k)
        k.setValue(list(rgb))
        if tip:
            k.setTooltip(tip)
        return k

    def div(name, label):
        g.addKnob(nuke.Text_Knob(name, label))

    pos = nuke.XY_Knob("center", "position")
    pos.setTooltip("Where the needle went in (plate pixels). Link to a Tracker to follow the skin.")
    g.addKnob(pos)
    pos.setValue([100, 100])
    dbl("amount", "amount", 1, 0, 1, "Overall strength of every layer. 0 = untouched plate.")

    div("div_punct", "Puncture")
    dbl("size", "size (px)", 2.5, 0.3, 30, "Radius of the puncture itself, in plate pixels.")
    dbl("stretch", "stretch", 1, 0.3, 4,
        "1 = round. Above 1 elongates the mark along 'angle' (an angled needle entry).")
    dbl("angle", "angle", 0, -180, 180, "Direction of the stretch, degrees.")
    col("core_color", "core colour", (0.35, 0.13, 0.11),
        "Multiplied over the plate inside the puncture. Pale (0.8,0.6,0.55) reads as an old healed scar.")
    dbl("core_opacity", "core opacity", 0.85, 0, 1)
    col("redness_color", "redness colour", (1.0, 0.62, 0.58),
        "Inflamed ring around the puncture.")
    dbl("redness_opacity", "redness opacity", 0.5, 0, 1)
    dbl("redness_spread", "redness spread", 4, 1, 12,
        "Redness radius as a multiple of the puncture size.")

    div("div_bruise", "Bruise halo")
    dbl("bruise_size", "bruise size (px)", 22, 0, 200, "Radius of the inner bruise, in plate pixels.")
    col("bruise_color", "bruise colour", (0.62, 0.50, 0.70), "Inner bruise: blue / purple.")
    dbl("bruise_opacity", "bruise opacity", 0.45, 0, 1, "0 = no bruise (fresh or old clean scar).")
    col("outer_color", "outer colour", (0.86, 0.88, 0.52),
        "Wider fringe, yellow / green. It is the 'older bruise' look.")
    dbl("outer_opacity", "outer opacity", 0.3, 0, 1)

    div("div_break", "Breakup")
    dbl("irregularity", "irregularity", 0.5, 0, 1,
        "How lumpy the edges are. 0 = perfect circles, which read as CG.")
    dbl("mottle", "mottle", 0.5, 0, 1, "Blotchy variation of the bruise density.")
    dbl("seed", "seed", 0, 0, 100, "Change it for a different shape. Do not animate it.")
    dbl("soften", "soften (px)", 0.8, 0, 20,
        "Blur on the masks. Raise it to match a soft or out of focus plate.")
    sm = nuke.Boolean_Knob("show_matte", "show matte")
    g.addKnob(sm)

    with g:
        src = nuke.nodes.Input(name="src")

        # ---- geometry: warped distances + mottle ------------------------------
        # Noise is sampled relative to "position" (plus a small offset so it never
        # lands exactly on the integer lattice, where Perlin noise is flat), so a
        # tracked position drags the shape along instead of swimming through it.
        SZ = "max({}size,0.05)".format(P)
        BS = "{}bruise_size".format(P)
        NX = "(x+0.5-{}center.x+0.37)".format(P)
        NY = "(y+0.5-{}center.y+0.37)".format(P)
        geo = nuke.nodes.Expression(name="Scar_geo", inputs=[src])
        ang = "radians(" + P + "angle)"
        u = "(x+0.5-" + P + "center.x)"
        v = "(y+0.5-" + P + "center.y)"
        k = "max({}stretch,0.01)".format(P)
        geo["temp_name0"].setValue("pu")
        geo["temp_expr0"].setValue("{u}*cos({a})+{v}*sin({a})".format(u=u, v=v, a=ang))
        geo["temp_name1"].setValue("pv")
        geo["temp_expr1"].setValue("-{u}*sin({a})+{v}*cos({a})".format(u=u, v=v, a=ang))
        # d: puncture + redness distance, takes the full stretch
        geo["temp_name2"].setValue("d")
        geo["temp_expr2"].setValue("sqrt(pow(pu/{k},2)+pow(pv*{k},2))".format(k=k))
        # db: bruise distance, only a mild share of the stretch (a bruise stays a blotch)
        geo["temp_name3"].setValue("db")
        geo["temp_expr3"].setValue(
            "sqrt(pow(pu/pow({k},0.3),2)+pow(pv*pow({k},0.3),2))".format(k=k))
        # r: puncture distance with a small jagged edge (2 octaves, below Nyquist otherwise)
        geo["expr0"].setValue(
            "max(d*(1+0.35*{i}*fBm({nx}/max({sz}+1,1.5),{ny}/max({sz}+1,1.5),{s}+7,2,2,0.5)),0.2*d)".format(
                i=P + "irregularity", nx=NX, ny=NY, sz=SZ, s=P + "seed"))
        # g: bruise distance with big slow lumps, tied to the bruise size
        geo["expr1"].setValue(
            "max(db*(1+0.7*{i}*fBm({nx}/max({b}*0.6,1),{ny}/max({b}*0.6,1),{s}+13,4,2,0.5)),0.2*db)".format(
                i=P + "irregularity", nx=NX, ny=NY, b=BS, s=P + "seed"))
        # b: mottle, 0..1
        geo["expr2"].setValue(
            "clamp(0.5+0.6*fBm({nx}/max({b}*0.25,1),{ny}/max({b}*0.25,1),{s}+29,4,2,0.5),0,1)".format(
                nx=NX, ny=NY, b=BS, s=P + "seed"))
        geo["expr3"].setValue("0")

        # ---- masks ------------------------------------------------------------
        m = nuke.nodes.Expression(name="Scar_masks", inputs=[geo])
        m["temp_name0"].setValue("f")
        m["temp_expr0"].setValue("max(0.35*{sz},0.35)".format(sz=SZ))
        m["temp_name1"].setValue("R")
        m["temp_expr1"].setValue("max({},0.5)".format(BS))
        m["temp_name2"].setValue("mo")
        m["temp_expr2"].setValue("1-{m}+{m}*b".format(m=P + "mottle"))
        m["expr0"].setValue("1-smoothstep({sz}-f,{sz}+f,r)".format(sz=SZ))
        m["expr1"].setValue("1-smoothstep({sz}*0.5,{sz}*max({sp},1.01),r)".format(
            sz=SZ, sp=P + "redness_spread"))
        # bruise_size = 0 switches both bruise layers off
        m["expr2"].setValue("({b}>0)*(1-smoothstep(0.1*R,R,g))*mo".format(b=BS))
        m["expr3"].setValue("({b}>0)*(1-smoothstep(0.55*R,1.6*R,g))*(0.7+0.3*mo)".format(b=BS))

        soft = nuke.nodes.Blur(name="Scar_soften", inputs=[m])
        soft["size"].setExpression(P + "soften")
        soft["channels"].setValue("rgba")

        # ---- grade chain, each limited by one matte channel -------------------
        def layer(name, prev, chan, color_knob, opacity_knob):
            gr = nuke.nodes.Grade(name=name)
            gr.setInput(0, prev)
            gr.setInput(1, soft)
            gr["maskChannelMask"].setValue(chan)
            # Without this Nuke keeps one value for all channels and only the
            # first expression survives the export.
            gr["multiply"].setSingleValue(False)
            for i, c in enumerate("rgb"):
                gr["multiply"].setExpression("{}{}.{}".format(P, color_knob, c), i)
            gr["mix"].setExpression("{}amount*{}{}".format(P, P, opacity_knob))
            return gr

        outer = layer("Scar_outer", src, "rgba.alpha", "outer_color", "outer_opacity")
        inner = layer("Scar_bruise", outer, "rgba.blue", "bruise_color", "bruise_opacity")
        red = layer("Scar_redness", inner, "rgba.green", "redness_color", "redness_opacity")
        core = layer("Scar_core", red, "rgba.red", "core_color", "core_opacity")

        sw = nuke.nodes.Switch(name="Scar_view", inputs=[core, soft])
        sw["which"].setExpression(P + "show_matte")

        nuke.nodes.Output(inputs=[sw])
    return g


def main():
    if nuke.env.get("gui"):
        raise SystemExit("Run this headless (Nuke -t). It clears the open script.")
    for n in nuke.allNodes():
        nuke.delete(n)
    g = build()
    for n in nuke.allNodes():
        n["selected"].setValue(n is g)
    tmp = OUT_PATH + ".tmp"
    nuke.nodeCopy(tmp)
    with open(tmp, newline="") as f:
        body = f.read().replace("\r\n", "\n")
    os.remove(tmp)
    with open(OUT_PATH, "w", newline="\n") as f:
        f.write(HEADER + body)
    print("WROTE", OUT_PATH)


if __name__ == "__main__":
    main()
