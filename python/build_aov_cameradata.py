"""Builds the AOV_CameraData Group and exports gizmos/AOV_CameraData.nk.

Target: Nuke 16 (baseline). Run headless:
    Nuke16.1.exe -t python/build_aov_cameradata.py

The exported .nk is a single top-level Group -- import it with
nuke.nodePaste(path), File > Import Script, or by pasting its text into the
node graph. It does NOT appear in the node toolbar (it is not a .gizmo).

What the group does with a camera-data pass (depth / N / P / Pref ...):
  * depth  -> depth.Z in Nuke's native 1/distance convention, with background
              (0 / inf / NaN / huge) mapped to 0, ready for ZDefocus (math = far=0).
  * N      -> maskN.alpha : soft mask by normal direction (world space).
  * P      -> maskP.alpha : soft mask by position (sphere or box, world units).
"""
import os
import nuke

OUT_PATH = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                        "gizmos", "AOV_CameraData.nk")

HEADER = """\
# AOV_CameraData -- camera-data utility group   (target: Nuke 16)
# Import: nuke.nodePaste("<path>/AOV_CameraData.nk"), File > Import Script, or paste
#         this text into the Node Graph. NOT a .gizmo -- it will not be in the toolbar.
# Input : an image carrying depth / N / P (/ Pref) layers (camera-data pass).
# Output: input + depth.Z (1/distance, ZDefocus "far=0"), maskN.alpha, maskP.alpha.
# Generated by python/build_aov_cameradata.py -- edit the script, not this file.
"""


def _layer(name, chans):
    nuke.Layer(name, ["%s.%s" % (name, c) for c in chans])


def _expr(inp, name, outch, expr):
    """Expression node writing `expr` to the single channel `outch`."""
    e = nuke.nodes.Expression(name=name, inputs=[inp])
    e["channel0"].setValue(outch)
    for i in (1, 2, 3):
        e["channel%d" % i].setValue("none")
    e["expr0"].setValue(expr)
    return e


def build():
    _layer("maskN", ["alpha"])
    _layer("maskP", ["alpha"])
    # source layers must exist now, or the channel knob defaults are saved as 'none'
    _layer("depth", ["Z"])
    _layer("N", ["red", "green", "blue"])
    _layer("P", ["red", "green", "blue"])

    g = nuke.nodes.Group(name="AOV_CameraData")

    def k(knob, flags_clear=None):
        g.addKnob(knob)
        return knob

    # The depth picker must be a Link_Knob to the internal Copy node's own channel
    # knob: a plain Channel_Knob round-trips depth.Z as the ambiguous name "depth"
    # (which Copy resolves to cutout.depth). So the Copy node is created first.
    with g:
        dcopy = nuke.nodes.Copy(name="Depth_select")
        dcopy["from0"].setValue("depth.Z")
        dcopy["to0"].setValue("depth.Z")

    # ---- UI ---------------------------------------------------------------
    k(nuke.Tab_Knob("tab_in", "Inputs"))
    lk = nuke.Link_Knob("depth_in", "depth channel")
    lk.makeLink(dcopy.fullName(), "from0")
    k(lk)
    k(nuke.Channel_Knob("n_layer", "normal layer", 3))
    k(nuke.Channel_Knob("p_layer", "position layer", 3))
    k(nuke.Text_Knob("in_hint", "",
                     "Position/normal layers must use .red/.green/.blue channels "
                     "(Nuke's default for R,G,B EXR channels)."))
    k(nuke.Boolean_Knob("do_reformat", "reformat (impulse filter)"))
    k(nuke.Format_Knob("fmt", "output format"))
    k(nuke.Text_Knob("ref_hint", "",
                     "Utility passes must never be filtered: impulse keeps depth/N/P "
                     "values unblended on resize."))

    k(nuke.Tab_Knob("tab_depth", "Depth"))
    k(nuke.Enumeration_Knob("depth_mode", "input is",
                            ["distance (convert to 1/z)", "already 1/z (pass through)"]))
    k(nuke.Double_Knob("depth_scale", "scene scale"))
    k(nuke.Double_Knob("bg_max", "background >="))
    k(nuke.Text_Knob("depth_hint", "",
                     "Output depth.Z = 1/(z*scale). 0 = infinity (background). "
                     "In ZDefocus: depth channel depth.Z, math = far=0."))

    k(nuke.Tab_Knob("tab_n", "Normal mask"))
    k(nuke.XYZ_Knob("n_dir", "direction"))
    b = nuke.PyScript_Knob("n_py", "+Y", "nuke.thisNode()['n_dir'].setValue([0, 1, 0])"); k(b)
    for lbl, v in (("-Y", (0, -1, 0)), ("+X", (1, 0, 0)), ("-X", (-1, 0, 0)),
                   ("+Z", (0, 0, 1)), ("-Z", (0, 0, -1))):
        pb = nuke.PyScript_Knob("n_p_" + lbl.replace("+", "p").replace("-", "m"), lbl,
                                "nuke.thisNode()['n_dir'].setValue(%s)" % (list(v),))
        pb.clearFlag(nuke.STARTLINE)
        k(pb)
    k(nuke.Double_Knob("n_angle", "angle (deg)"))
    k(nuke.Double_Knob("n_soft", "softness (deg)"))
    k(nuke.Boolean_Knob("n_invert", "invert"))

    k(nuke.Tab_Knob("tab_p", "Position mask"))
    k(nuke.Enumeration_Knob("p_shape", "shape", ["sphere", "box"]))
    k(nuke.XYZ_Knob("p_center", "center"))
    k(nuke.Double_Knob("p_radius", "radius (sphere)"))
    k(nuke.XYZ_Knob("p_size", "half size (box)"))
    k(nuke.Double_Knob("p_falloff", "falloff"))
    k(nuke.Boolean_Knob("p_invert", "invert"))
    k(nuke.XY_Knob("p_pick", "pick pixel"))
    k(nuke.PyScript_Knob("p_pick_btn", "set center from pixel", (
        "n = nuke.thisNode()\n"
        "L = n['p_layer'].value()\n"
        "x, y = n['p_pick'].value()\n"
        "src = n.input(0)\n"
        "n['p_center'].setValue([src.sample(L + '.' + c, x, y) for c in ('red', 'green', 'blue')])\n")))

    k(nuke.Tab_Knob("tab_out", "Output"))
    k(nuke.Enumeration_Knob("view", "view in rgba",
                            ["off", "normal mask", "position mask", "depth (1/z, x gain)"]))
    k(nuke.Double_Knob("view_gain", "depth view gain"))

    # defaults
    g["n_layer"].setValue("N")
    g["p_layer"].setValue("P")
    g["depth_scale"].setValue(1.0)
    g["bg_max"].setValue(1e9)
    g["n_dir"].setValue([0, 1, 0])
    g["n_angle"].setValue(30.0)
    g["n_soft"].setValue(15.0)
    g["p_center"].setValue([0, 0, 0])
    g["p_radius"].setValue(100.0)
    g["p_size"].setValue([100, 100, 100])
    g["p_falloff"].setValue(20.0)
    g["view_gain"].setValue(1.0)

    # ---- internals --------------------------------------------------------
    with g:
        inp = nuke.nodes.Input(name="src")
        rf = nuke.nodes.Reformat(name="Reformat_impulse", inputs=[inp])
        rf["type"].setValue("to format")
        rf["resize"].setValue("width")
        rf["filter"].setValue("impulse")
        rf["format"].setExpression("parent.fmt")
        rf["disable"].setExpression("!parent.do_reformat")

        # Copy moves the picked channel into depth.Z (see Link_Knob note above).
        dcopy.setInput(0, rf)
        dcopy.setInput(1, rf)

        D = "depth.Z"
        depth = _expr(
            dcopy, "Depth_to_1overZ", "depth.Z",
            "parent.depth_mode == 0 ? "
            "((%s > 0 && %s < parent.bg_max) ? 1/(%s * parent.depth_scale) : 0) : "
            "((%s > 0 && %s < parent.bg_max) ? %s : 0)" % ((D,) * 6))

        NL = "[value parent.n_layer]"
        dot = ("(%s.red*parent.n_dir.x + %s.green*parent.n_dir.y + %s.blue*parent.n_dir.z)"
               " / max(sqrt(%s.red*%s.red + %s.green*%s.green + %s.blue*%s.blue), 1e-6)"
               " / max(sqrt(parent.n_dir.x*parent.n_dir.x + parent.n_dir.y*parent.n_dir.y"
               " + parent.n_dir.z*parent.n_dir.z), 1e-6)") % ((NL,) * 9)
        c_in = "cos(radians(parent.n_angle))"
        c_out = "cos(radians(min(parent.n_angle + parent.n_soft, 180)))"
        nmask = _expr(
            depth, "NormalMask", "maskN.alpha",
            "abs(parent.n_invert - clamp((%s - %s) / max(%s - %s, 1e-6)))" % (dot, c_out, c_in, c_out))

        PL = "[value parent.p_layer]"
        dx = "(%s.red - parent.p_center.x)" % PL
        dy = "(%s.green - parent.p_center.y)" % PL
        dz = "(%s.blue - parent.p_center.z)" % PL
        sdf = ("parent.p_shape == 0 ? "
               "(sqrt(%s*%s + %s*%s + %s*%s) - parent.p_radius) : "
               "max(abs%s - parent.p_size.x, max(abs%s - parent.p_size.y, abs%s - parent.p_size.z))"
               % (dx, dx, dy, dy, dz, dz, dx, dy, dz))
        psdf = _expr(nmask, "PosSDF", "maskP.alpha", sdf)
        pmask = _expr(
            psdf, "PositionMask", "maskP.alpha",
            "abs(parent.p_invert - (1 - clamp(maskP.alpha / max(parent.p_falloff, 1e-6))))")

        view = nuke.nodes.Expression(name="View", inputs=[pmask])
        for i, ch in enumerate(("rgba.red", "rgba.green", "rgba.blue")):
            view["channel%d" % i].setValue(ch)
            view["expr%d" % i].setValue(
                "parent.view == 1 ? maskN.alpha : parent.view == 2 ? maskP.alpha : "
                "depth.Z * parent.view_gain")
        view["channel3"].setValue("none")
        view["disable"].setExpression("parent.view == 0")

        nuke.nodes.Output(inputs=[view])
    return g


def main():
    for n in nuke.allNodes():
        nuke.delete(n)
    g = build()
    nuke.selectAll()
    for n in nuke.allNodes():
        n["selected"].setValue(n is g)
    tmp = OUT_PATH + ".tmp"
    nuke.nodeCopy(tmp)
    with open(tmp) as f:
        body = f.read()
    os.remove(tmp)
    with open(OUT_PATH, "w") as f:
        f.write(HEADER + body)
    print("WROTE", OUT_PATH)


main()
