"""Builds the SecurityWire Group and exports gizmos/SecurityWire.nk.

Target: Nuke 16 (baseline). Run headless:
    Nuke16.1.exe -t python/build_security_wire.py

Procedural diamond wire mesh (security / wired-glass window), fully analytic:
two families of parallel lines evaluated per pixel in Expression nodes, so it
is resolution independent and needs no input.

Expr "Wire_masks" writes:  r = wire mask (AA), g = soft drop shadow,
                           b = rim highlight, a = cell gradient (0 at wire, 1 at cell centre)
Expr "Wire_shade" turns those into the final colour, alpha = wire mask.
"""
import os
import nuke

OUT_PATH = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                        "gizmos", "SecurityWire.nk")

HEADER = """\
# SecurityWire -- procedural diamond wire mesh texture (wired glass / security window)   (target: Nuke 16)
# Import: nuke.nodePaste("<path>/SecurityWire.nk"), File > Import Script, or paste
#         this text into the Node Graph. NOT a .gizmo -- it will not be in the toolbar.
# Input : none (generator). Set the format on the node.
# Output: rgb = textured mesh, alpha = wire mask (use it to drive glass/refraction etc).
# Tested: built and rendered headless in Nuke 16.1v4.
# Generated by python/build_security_wire.py -- edit the script, not this file.
"""

S = "parent.spacing"
W = "(parent.wire_width/2)"
F = "max(parent.softness,0.01)"
SS = "max(parent.shadow_soft,0.01)"


def dist(q):
    """Pixel distance from coordinate q to the nearest line of its family."""
    return "abs(({q})-{S}*floor(({q})/{S}+0.5))".format(q=q, S=S)


def line(q, soft=F):
    return "(1-smoothstep({W}-{f},{W}+{f},{d}))".format(W=W, f=soft, d=dist(q))


def build():
    g = nuke.nodes.Group(name="SecurityWire")
    g["tile_color"].setValue(0x5a6262ff)

    g.addKnob(nuke.Tab_Knob("tab_wire", "SecurityWire"))
    fmt = nuke.Link_Knob("format", "format")
    g.addKnob(fmt)

    def dbl(name, label, val, lo, hi, tip):
        k = nuke.Double_Knob(name, label)
        k.setRange(lo, hi)
        k.setValue(val)
        k.setTooltip(tip)
        g.addKnob(k)
        return k

    g.addKnob(nuke.Text_Knob("div_shape", "Pattern"))
    dbl("spacing", "cell size", 80, 4, 400, "Distance in pixels between parallel wires.")
    dbl("opening", "diamond angle", 90, 20, 160,
        "Angle between the two wire families. 90 = square diamonds, lower = taller diamonds.")
    dbl("rotate", "rotate", 0, -180, 180, "Rotates the whole mesh.")
    c = nuke.XY_Knob("center", "offset")
    c.setTooltip("Slides the mesh (pixels).")
    g.addKnob(c)
    dbl("wire_width", "wire width", 3, 0, 20, "Wire thickness in pixels.")
    dbl("softness", "softness", 0.9, 0, 10, "Edge falloff of the wire in pixels (antialiasing).")

    g.addKnob(nuke.Text_Knob("div_look", "Look"))
    bg = nuke.AColor_Knob("bg_color", "background")
    g.addKnob(bg)
    bg.setValue([0.10, 0.11, 0.11, 1.0])
    wc = nuke.AColor_Knob("wire_color", "wire")
    g.addKnob(wc)
    wc.setValue([0.055, 0.06, 0.06, 1.0])
    dbl("cell_shade", "cell shading", 0.15, 0, 1,
        "Brightens cell centres / darkens near the wires.")
    so = nuke.XY_Knob("shadow_offset", "shadow offset")
    g.addKnob(so)
    so.setValue([1.5, -1.5])
    dbl("shadow_soft", "shadow softness", 2.5, 0, 20, "")
    dbl("shadow_opacity", "shadow opacity", 0.35, 0, 1, "")
    dbl("highlight", "rim highlight", 0.03, 0, 0.5,
        "Light edge on the side of the wire facing away from the shadow.")
    dbl("grain", "grain", 0.08, 0, 1, "Multiplicative per-pixel noise.")
    dbl("grain_seed", "grain seed", 0, 0, 100, "Animate (e.g. =frame) for boiling grain.")

    with g:
        const = nuke.nodes.Constant(name="Constant1")
        const["color"].setValue([0, 0, 0, 0])
        fmt.makeLink(const.name(), "format")

        a1 = "radians(parent.rotate+parent.opening/2)"
        a2 = "radians(parent.rotate+180-parent.opening/2)"
        px = "(x+0.5-parent.center.x)"
        py = "(y+0.5-parent.center.y)"

        m = nuke.nodes.Expression(name="Wire_masks", inputs=[const])
        m["temp_name0"].setValue("u")
        m["temp_expr0"].setValue("{px}*cos({a})+{py}*sin({a})".format(px=px, py=py, a=a1))
        m["temp_name1"].setValue("v")
        m["temp_expr1"].setValue("{px}*cos({a})+{py}*sin({a})".format(px=px, py=py, a=a2))
        m["temp_name2"].setValue("su")
        m["temp_expr2"].setValue(
            "parent.shadow_offset.x*cos({a})+parent.shadow_offset.y*sin({a})".format(a=a1))
        m["temp_name3"].setValue("sv")
        m["temp_expr3"].setValue(
            "parent.shadow_offset.x*cos({a})+parent.shadow_offset.y*sin({a})".format(a=a2))
        # r: wire
        m["expr0"].setValue("max({},{})".format(line("u"), line("v")))
        # g: drop shadow (wire shifted by the offset, softer)
        m["expr1"].setValue("max({},{})".format(line("u-su", SS), line("v-sv", SS)))
        # b: rim highlight (wire shifted the other way, minus the wire itself)
        m["expr2"].setValue("max(clamp({}-{},0,1),clamp({}-{},0,1))".format(
            line("u+su"), line("u"), line("v+sv"), line("v")))
        # a: cell gradient
        m["expr3"].setValue("clamp(min({},{})/({}/2),0,1)".format(dist("u"), dist("v"), S))

        sh = nuke.nodes.Expression(name="Wire_shade", inputs=[m])
        sh["temp_name0"].setValue("gr")
        sh["temp_expr0"].setValue("1+parent.grain*(random(x,y,parent.grain_seed)-0.5)")
        for i, ch in enumerate("rgb"):
            sh["expr%d" % i].setValue(
                "((parent.bg_color.{c}*(1+parent.cell_shade*(a-0.5))*(1-parent.shadow_opacity*g)"
                "+parent.highlight*b)*(1-r)+parent.wire_color.{c}*r)*gr".format(c=ch))
        sh["expr3"].setValue("r")

        nuke.nodes.Output(inputs=[sh])
    return g


def main():
    for n in nuke.allNodes():
        nuke.delete(n)
    g = build()
    for n in nuke.allNodes():
        n["selected"].setValue(n is g)
    tmp = OUT_PATH + ".tmp"
    nuke.nodeCopy(tmp)
    with open(tmp) as f:
        body = f.read()
    os.remove(tmp)
    with open(OUT_PATH, "w") as f:
        f.write(HEADER + body)
    print("WROTE", OUT_PATH)


if __name__ == "__main__":
    main()
